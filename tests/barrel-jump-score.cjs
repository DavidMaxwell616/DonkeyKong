const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const GameScene = vm.runInNewContext(fs.readFileSync('js/GameScene.js', 'utf8')
    .replace(/^import .*;\r?\n/gm, '').replace('export default class GameScene', 'class GameScene')
    + '\nGameScene;', { Phaser: { Scene: class {} } });
const scene = new GameScene();
scene.mario = { x: 50, y: 80 };
scene.marioPhysics = { isJumping: true };
scene.jumpScoredBarrels = new Set();
scene.barrels = new Set([{ active: true, x: 50, y: 100 }]);
scene.hud = { values: { score: 0, highScore: 50 }, setValues(v) { Object.assign(this.values, v); } };
scene.updateBarrelJumpScore();
scene.updateBarrelJumpScore();
assert.equal(scene.hud.values.score, 100, 'One award per barrel per jump');
assert.equal(scene.hud.values.highScore, 100);
scene.marioPhysics.isJumping = false;
scene.updateBarrelJumpScore();
assert.equal(scene.hud.values.score, 100, 'Walking earns no points');
scene.marioPhysics.isJumping = true;
scene.mario.y = 95;
scene.updateBarrelJumpScore();
assert.equal(scene.hud.values.score, 100, 'Insufficient clearance earns no points');
scene.mario.y = 40;
scene.updateBarrelJumpScore();
assert.equal(scene.hud.values.score, 100, 'Barrels on lower floors earn no points');
scene.mario.y = 80;
scene.updateBarrelJumpScore();
assert.equal(scene.hud.values.score, 200, 'A later jump can score again');
scene.barrels.add({ active: true, x: 52, y: 100 });
scene.updateBarrelJumpScore();
assert.equal(scene.hud.values.score, 400, 'Two barrels in one jump earn 300 total');
assert.equal(scene.hud.values.highScore, 400);
scene.updateBarrelJumpScore();
assert.equal(scene.hud.values.score, 400, 'Two-barrel bonus is awarded only once');
scene.marioPhysics.isJumping = false;
scene.updateBarrelJumpScore();
scene.marioPhysics.isJumping = true;
scene.updateBarrelJumpScore();
assert.equal(scene.hud.values.score, 700, 'A new two-barrel jump earns another 300');
console.log('PASS: barrel jump scoring, deduplication, clearance and high score');
