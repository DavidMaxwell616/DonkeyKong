const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
let side = 0;
const Scene = vm.runInNewContext(fs.readFileSync('js/Level4Scene.js', 'utf8').replace(/^import .*;\r?\n/gm, '').replace('export default class Level4Scene', 'class Level4Scene') + '\nLevel4Scene;', { Phaser: { Scene: class {}, Math: { Between: (min, max) => min === 0 ? side : 2 } }, GODMODE: false });
const scene = new Scene();
const layout = JSON.parse(fs.readFileSync('assets/levels/level-4.json', 'utf8'));
const spawns = [];
scene.fireHunters = { level: layout, spawnAt: (row, x) => spawns.push({ row, x }), update() {} };
scene.flameElapsed = 0;
scene.flameSpawnDelay = 6000;
for (let i = 0; i < 119; i++) scene.updateFlames(50);
assert.equal(spawns.length, 0);
scene.updateFlames(50);
assert.equal(spawns[0].x, 29);
const firstDelay = scene.flameSpawnDelay;
side = 1;
while (spawns.length < 2) scene.updateFlames(50);
assert.equal(spawns[1].x, 195);
assert(scene.flameSpawnDelay < firstDelay);
while (scene.flameElapsed < 95000) scene.updateFlames(50);
assert.equal(scene.flameSpawnDelay <= 1500, true);
scene.flameSpawnDelay = 0;
scene.updateFlames(50);
assert.equal(scene.flameSpawnDelay, 1500, 'Spawn interval has a lower bound');
const count = spawns.length;
scene.finished = true;
scene.flameSpawnDelay = 0;
scene.updateFlames(50);
assert.equal(spawns.length, count, 'Completion stops spawning');
scene.finished = false;
scene.marioDying = true;
scene.updateFlames(50);
assert.equal(spawns.length, count, 'Death stops spawning');
console.log('PASS: level 4 left/right spawns, increasing frequency, minimum interval and stopping');
